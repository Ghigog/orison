#[derive(Debug, Clone, PartialEq)]
pub enum HealthStatus {
    Available,
    /// The endpoint answered but the configured model is not present there.
    ModelNotInstalled,
    /// The endpoint itself could not be reached.
    Unreachable {
        detail: String,
    },
}

/// The direct fix for B-15. In the Godot build, `LLMClient.send_prompt()`
/// treated an HTTP 404 for a missing model no differently from a normal
/// non-streaming failure: `request_failed` fired, but nothing forced a
/// caller to check for it, so "RAPTOR summaries generated successfully" could
/// print over an empty result. `health()` returns this type and every
/// backend implementation must answer it truthfully before any caller may
/// print a success message.
#[derive(Debug, Clone, PartialEq)]
pub struct ModelHealth {
    pub model: String,
    pub status: HealthStatus,
    pub context_length: Option<usize>,
}

impl ModelHealth {
    pub fn is_available(&self) -> bool {
        self.status == HealthStatus::Available
    }
}
